/**
 * Embed each src/skills/builtin/<name>/SKILL.md (+ companion files) into
 * src/skills/builtin.generated.ts so packaged desktop binaries still expose
 * slash skills without reading the source tree at runtime.
 */
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BUILTIN_DIR = join(ROOT, "src", "skills", "builtin");
const OUT = join(ROOT, "src", "skills", "builtin.generated.ts");

function parseFrontmatter(text: string): { meta: Record<string, string>; body: string } {
  if (!text.startsWith("---")) return { meta: {}, body: text };
  const end = text.indexOf("\n---", 3);
  if (end === -1) return { meta: {}, body: text };
  const header = text.slice(3, end).trim();
  const body = text.slice(end + 4).replace(/^\r?\n/, "");
  const meta: Record<string, string> = {};
  let currentKey = "";
  let blockMode: "folded" | "literal" | null = null;
  for (const line of header.split(/\r?\n/)) {
    const block = /^([A-Za-z0-9_-]+)\s*:\s*([>|][+-]?)\s*$/.exec(line);
    if (block) {
      currentKey = block[1].toLowerCase();
      meta[currentKey] = "";
      blockMode = block[2].startsWith(">") ? "folded" : "literal";
      continue;
    }
    const match = /^([A-Za-z0-9_-]+)\s*:\s*(.*)$/.exec(line);
    if (match) {
      currentKey = match[1].toLowerCase();
      blockMode = null;
      meta[currentKey] = match[2].replace(/^["']|["']$/g, "").trim();
      continue;
    }
    if (currentKey && /^\s+/.test(line)) {
      const value = line.trim();
      if (blockMode === "literal") {
        meta[currentKey] = meta[currentKey] ? `${meta[currentKey]}\n${value}` : value;
      } else {
        meta[currentKey] = `${meta[currentKey]} ${value}`.trim();
      }
    }
  }
  return { meta, body };
}

function normalizeName(raw: string, fallback: string): string {
  return (raw || fallback)
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
}

function asTsString(value: string): string {
  return JSON.stringify(value);
}

const skills: Array<{
  folder: string;
  name: string;
  description: string;
  skillMd: string;
  files: Record<string, string>;
}> = [];

for await (const entry of Deno.readDir(BUILTIN_DIR)) {
  if (!entry.isDirectory || entry.name.startsWith(".")) continue;
  const dir = join(BUILTIN_DIR, entry.name);
  const skillPath = join(dir, "SKILL.md");
  const skillMd = await Deno.readTextFile(skillPath).catch(() => null);
  if (!skillMd) continue;
  const { meta } = parseFrontmatter(skillMd);
  const name = normalizeName(meta.name ?? "", entry.name);
  const description = (meta.description ?? "").trim();
  const files: Record<string, string> = { "SKILL.md": skillMd };
  for await (const file of Deno.readDir(dir)) {
    if (!file.isFile || file.name === "SKILL.md" || file.name.startsWith(".")) continue;
    if (!/\.(md|txt|json|yaml|yml)$/i.test(file.name)) continue;
    const text = await Deno.readTextFile(join(dir, file.name)).catch(() => null);
    if (text != null) files[file.name] = text;
  }
  skills.push({ folder: entry.name, name, description, skillMd, files });
}

skills.sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  "// Generated by scripts/embed-builtin-skills.ts — do not edit.",
  "export interface EmbeddedBuiltinSkill {",
  "  folder: string;",
  "  name: string;",
  "  description: string;",
  "  skillMd: string;",
  "  files: Record<string, string>;",
  "}",
  "",
  "export const BUILTIN_SKILLS: EmbeddedBuiltinSkill[] = [",
];

for (const skill of skills) {
  const fileEntries = Object.entries(skill.files)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, text]) => `    ${asTsString(name)}: ${asTsString(text)},`)
    .join("\n");
  lines.push("  {");
  lines.push(`    folder: ${asTsString(skill.folder)},`);
  lines.push(`    name: ${asTsString(skill.name)},`);
  lines.push(`    description: ${asTsString(skill.description)},`);
  lines.push(`    skillMd: ${asTsString(skill.skillMd)},`);
  lines.push("    files: {");
  lines.push(fileEntries);
  lines.push("    },");
  lines.push("  },");
}

lines.push("];");
lines.push("");

await Deno.writeTextFile(OUT, lines.join("\n"));
console.log(`Wrote ${skills.length} builtin skills → ${OUT}`);
